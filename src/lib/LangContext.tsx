export { translations }

export type TranslationKey = keyof typeof translations.fr

const LangContext = createContext<{
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: TranslationKey) => string
}>({ lang: 'fr', setLang: () => {}, t: (k) => k })

export function LangProvider({ children }: { children: React.ReactNode }) {
  const { user } = useAuth()
  const [lang, setLangState] = useState<Lang>('fr')

  useEffect(() => {
    const saved = localStorage.getItem('lang') as Lang
    if (saved === 'fr' || saved === 'en' || saved === 'de') { setLangState(saved); return }
    const geo = document.cookie.split(';').find(c => c.trim().startsWith('geo-lang='))?.split('=')?.[1]?.trim() as Lang | undefined
    if (geo === 'fr' || geo === 'en' || geo === 'de') { setLangState(geo); return }
    const browser: Lang = navigator.language.startsWith('en') ? 'en' : navigator.language.startsWith('de') ? 'de' : 'fr'
    setLangState(browser)
  }, [])

  // Synchronise sur le profil pour que le serveur (crons, notifications push)
  // puisse écrire dans la bonne langue — localStorage seul n'est lisible que
  // côté client, le serveur n'y a jamais accès.
  useEffect(() => {
    if (!user) return
    supabase.from('profiles').update({ preferred_lang: lang }).eq('id', user.id).then(() => {})
  }, [user, lang])

  const setLang = (l: Lang) => {
    setLangState(l)
    localStorage.setItem('lang', l)
  }

  const t = (key: TranslationKey): string => translations[lang][key] || translations.fr[key] || key

  return (
    <LangContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LangContext.Provider>
  )
}

export const useLang = () => useContext(LangContext)
